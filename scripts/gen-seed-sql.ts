// יוצר את קובץ ה־SQL של הנתונים ההתחלתיים מתוך src/lib/seed-catalog.ts.
// שימו לב: מיגרציה 004 כבר הוחלה על Supabase (שלב 2). שינויים בנתונים מאז נכתבים במיגרציות חדשות (005 ואילך), ולא מריצים את זה שוב.
// הרצה (לבדיקה בלבד, מדפיס למסך): npm run seed:sql
import { seedCatalog } from "../src/lib/seed-catalog.ts";

const q = (s: string | null | undefined) => (s === null || s === undefined ? "null" : `'${s.replace(/'/g, "''")}'`);
const n = (x: number | null | undefined) => (x === null || x === undefined ? "null" : String(x));
const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(",")}]::text[]` : "'{}'::text[]");
const out: string[] = [];
const { categories, products, bundles, settings } = seedCatalog;

out.push("-- Generated by scripts/gen-seed-sql.ts from src/lib/seed-catalog.ts. Do not edit by hand.");
out.push("-- Initial catalog from the owner's sheet (2026-11-18). No cost prices here by design.");
out.push("begin;");
categories.forEach((c, i) =>
  out.push(`insert into public.categories (name, slug, sort_order) values (${q(c.name)}, ${q(c.slug)}, ${i}) on conflict (slug) do nothing;`));

products.forEach((p, i) => {
  out.push(`insert into public.products (id, code, name, slug, description, base_price_agorot, prep_days, is_active, allowed_in_bundles, sort_order, stock_mode, stock_qty, is_available, deal_qty, deal_price_agorot)
  values (${q(p.id)}, ${q(p.code)}, ${q(p.name)}, ${q(p.slug)}, ${q(p.description)}, ${p.priceAgorot}, ${settings.pickupBusinessDays}, true, ${p.allowedInBundles}, ${i}, ${q(p.stockMode)}, ${n(p.stockQty)}, ${p.isAvailable}, ${n(p.deal?.qty)}, ${n(p.deal?.priceAgorot)});`);
  out.push(`insert into public.product_categories (product_id, category_id) select ${q(p.id)}, id from public.categories where slug = ${q(p.categorySlug)};`);
  p.designOptions.forEach((o, j) =>
    out.push(`insert into public.product_design_options (product_id, key, label, help_text, sort_order) values (${q(p.id)}, ${q(o.key)}, ${q(o.label)}, ${q(o.help ?? "")}, ${j});`));
  p.fields.forEach((f, j) =>
    out.push(`insert into public.customization_fields (product_id, key, label, type, required, max_length, max_words, options, help_text, min_images, max_images, design_option_key, sort_order)
  values (${q(p.id)}, ${q(f.key)}, ${q(f.label)}, ${q(f.type)}, ${f.required}, ${n(f.maxLength)}, ${n(f.maxWords)}, ${arr(f.options ?? [])}, ${q(f.help ?? "")}, ${f.minImages ?? 0}, ${f.maxImages ?? 1}, ${q(f.optionKey)}, ${j});`));
});

bundles.forEach((b, i) => {
  out.push(`insert into public.bundle_templates (id, code, name, slug, description, type, fixed_price_agorot, min_items, max_items, is_active, sort_order)
  values (${q(b.id)}, ${q(b.code)}, ${q(b.name)}, ${q(b.slug)}, ${q(b.description)}, ${q(b.type)}, ${n(b.priceAgorot)}, ${b.minItems}, ${n(b.maxItems)}, true, ${i});`);
  b.items.forEach((it) =>
    out.push(`insert into public.fixed_bundle_items (bundle_template_id, product_id, quantity) values (${q(b.id)}, ${q(it.productId)}, ${it.qty});`));
});

out.push(`update public.shop_settings set courier_fee_agorot = ${settings.courierFeeAgorot}, pickup_business_days = ${settings.pickupBusinessDays}, courier_business_days = ${settings.courierBusinessDays}, pickup_city = ${q(settings.pickupCity)};`);
out.push("commit;");
console.log(out.join("\n"));
